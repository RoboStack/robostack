"""update-conda-forge-pinning: distributions on the shared pinning move together."""

import maintenance
import robostack as rs


def _setup(monkeypatch, own):
    monkeypatch.setattr(rs, "distros", lambda: ["humble", "jazzy", "rolling"])
    monkeypatch.setattr(rs, "settings", lambda d: {"conda_forge_pinning_version": "1"} if d in own else {})
    calls = []
    monkeypatch.setattr(maintenance, "update_shared_pinning",
                        lambda: calls.append("shared") or maintenance.Result("shared", "s"))
    return calls


def test_a_distribution_on_the_shared_pinning_updates_all_of_them(monkeypatch):
    calls = _setup(monkeypatch, own=set())
    assert maintenance.uses_shared_pinning("jazzy")
    assert maintenance.update_pinning("jazzy").title == "shared"
    assert calls == ["shared"]


def test_repository_wide_update_runs_the_shared_one_once(monkeypatch, tmp_path):
    calls = _setup(monkeypatch, own={"rolling"})
    monkeypatch.setattr(maintenance, "update_pinning",
                        lambda d: calls.append(d) or maintenance.Result(d, d))
    assert maintenance.main("update-pinning", ["--summary", str(tmp_path / "s.md")]) == 0
    assert calls == ["shared", "rolling"]


def test_no_shared_update_when_every_distribution_has_its_own(monkeypatch, tmp_path):
    calls = _setup(monkeypatch, own={"humble", "jazzy", "rolling"})
    monkeypatch.setattr(maintenance, "update_pinning",
                        lambda d: calls.append(d) or maintenance.Result(d, d))
    maintenance.main("update-pinning", ["--summary", str(tmp_path / "s.md")])
    assert calls == ["humble", "jazzy", "rolling"]


def test_pin_report_lists_the_direct_users():
    changed = {"shaderc": ("2026.3", "2026.4"), "zig-compiler": (None, "zig"), "libgdal": (["11.4.2"], ["10.7.4", "11.4.3"])}
    packages = {"gz_ogre_next_vendor": "uses shaderc", "gz_rendering_vendor": "depends on gz_ogre_next_vendor"}
    lines = maintenance.pin_report(changed, packages)
    assert lines[:3] == ["| changed pin | before → after | used directly by |", "|---|---|---|",
                         "| `shaderc` | `2026.3` → `2026.4` | `gz_ogre_next_vendor` |"]
    assert "- `libgdal`: `11.4.2` → `10.7.4, 11.4.3`" in lines
    assert "- `zig-compiler`: `(none)` → `zig`" in lines
    # nothing used: the folded list comes first
    assert maintenance.pin_report({"zig-compiler": (None, "zig")}, {})[0] == "<details>"


def test_vinca_pinning_keeps_selectors_and_replaces_shared_entries(monkeypatch, tmp_path):
    (tmp_path / "pinning").mkdir()
    (tmp_path / "pinning" / "conda_forge.yaml").write_text("# header\nconda_forge_pinning_version: '1'\nmigrations: []\n")
    (tmp_path / "pinning" / "overrides.yaml").write_text(
        "pinning_overrides:\n"
        "  # why channels are dropped\n"
        "  channel_sources: null\n"
        "  # why glibc is pinned\n"
        "  glibc:\n"
        "    - 2.28   # [not riscv64]\n"
        "    - 2.39   # [riscv64]\n"
        "  # why python is pinned\n"
        "  python:\n"
        "    - 3.14.*\n"
        "  # why lua is pinned\n"
        "  lua:\n"
        "    - 5.4\n"
    )
    (tmp_path / "x").mkdir()
    (tmp_path / "x" / "distro.yaml").write_text(
        "pinning_overrides:\n"
        "  xtensor: ['0.25.0']\n"
        "  # not carried over\n"
        "  python:\n"
        "    - 3.12.*   # [not riscv64]\n"
        "    - 3.14.*\n"
        "# nor is this one\n"
        "rosdistro_sync: x/2026-01-01\n"
    )
    monkeypatch.setattr(rs, "SHARED", tmp_path)
    monkeypatch.setattr(rs, "DISTROS", tmp_path)
    assert rs.vinca_pinning("x") == (
        "# Generated by `pixi run rs x render-pinning` from shared/pinning/ and\n"
        "# distros/x/distro.yaml; edit those instead.\n"
        "conda_forge_pinning_version: '1'\n"
        "migrations: []\n"
        "pinning_overrides:\n"
        "  # why channels are dropped\n"
        "  channel_sources:\n"
        "  # why glibc is pinned\n"
        "  glibc:\n"
        "    - 2.28   # [not riscv64]\n"
        "    - 2.39   # [riscv64]\n"
        "  # why lua is pinned\n"
        "  lua:\n"
        "    - 5.4\n"
        "  # ros-x specific (distros/x/distro.yaml)\n"
        "  xtensor:\n"
        "    - '0.25.0'\n"
        "  python:\n"
        "    - 3.12.*   # [not riscv64]\n"
        "    - 3.14.*\n"
    )
